<?php

namespace MxApi\Core\Endpoint;

use MxApi\Core\Http\Request;

/**
 * Эндпоинт, умеющий назвать версию ответа, не собирая его.
 *
 * Без этого интерфейса ядро тоже отдаёт 304, но лишь посчитав тело целиком:
 * экономится трафик, а не работа. Реализация нужна там, где версию выборки
 * видно дёшево (последнее изменение, счётчик ревизий) — тогда повторный
 * инкрементальный запрос не доходит до handle() вовсе.
 *
 * Интерфейс отдельный, а не метод в EndpointInterface: добавить метод в уже
 * реализованный кем-то интерфейс — значит сломать все сторонние эндпоинты.
 *
 * @api Реализуется провайдерами.
 */
interface EtagAwareInterface
{
    /**
     * Версия ответа для этих параметров запроса.
     *
     * Обязана меняться при любом изменении данных, попадающих в ответ, и
     * различаться для разных параметров: одна метка на все выборки эндпоинта
     * отдаст клиенту чужой срез. Считать её дорого нельзя — иначе смысл
     * теряется.
     *
     * @param Request $request
     * @param EndpointContext $context
     * @return string|null null — версию сейчас не определить, ответ собирается обычным путём.
     */
    public function computeEtag(Request $request, EndpointContext $context);
}
